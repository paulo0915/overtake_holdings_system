"""Re-upsert DuPont Registry classified records from local CSV into Supabase.

Uses a fast bulk-insert path (batches of 100) when no prior DuPont records
exist in the DB, falling back to per-row lifecycle upsert if partial data exists.

Run from overtake_holdings_system/:
    python scripts/reupsert_dupont.py
"""

import csv
import logging
import sys
import uuid
from pathlib import Path

PROJECT_ROOT = Path(__file__).parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

if sys.platform == "win32":
    import io
    if hasattr(sys.stdout, "buffer"):
        sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")
    if hasattr(sys.stderr, "buffer"):
        sys.stderr = io.TextIOWrapper(sys.stderr.buffer, encoding="utf-8", errors="replace")

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s | %(levelname)-8s | %(name)s | %(message)s",
    handlers=[logging.StreamHandler(sys.stdout)],
)
log = logging.getLogger(__name__)

CSV_PATH = PROJECT_ROOT / "output" / "dupont_registry_classifieds.csv"
SOURCE_DOMAIN = "dupontregistry.com"
BATCH_SIZE = 100

_INT_FIELDS = {"Year", "Mileage_mi", "Asking_price", "Asking_price_USD", "Previous_asking_price"}
_FLOAT_FIELDS = {"FX_rate_used"}
_DROP_COLS = {"Record_ID"}  # auto-generated by DB


def _coerce(key: str, val: str):
    if val == "" or val is None:
        return None
    if key in _INT_FIELDS:
        try:
            return int(float(val))
        except (ValueError, TypeError):
            return None
    if key in _FLOAT_FIELDS:
        try:
            return float(val)
        except (ValueError, TypeError):
            return None
    return val


def load_csv(path: Path) -> list[dict]:
    records = []
    with open(path, newline="", encoding="utf-8-sig") as f:
        reader = csv.DictReader(f)
        for row in reader:
            rec = {k: _coerce(k, v) for k, v in row.items() if k not in _DROP_COLS}
            records.append(rec)
    log.info("Loaded %d records from %s", len(records), path)
    return records


def bulk_insert(client, records: list[dict]) -> int:
    """Batch-insert all records, assigning UUIDs and setting listing_status."""
    inserted = 0
    for i in range(0, len(records), BATCH_SIZE):
        batch_raw = records[i: i + BATCH_SIZE]
        batch = []
        for rec in batch_raw:
            row = {k.lower(): v for k, v in rec.items()}
            row["record_id"] = str(uuid.uuid4())
            row.setdefault("listing_status", "active")
            if row.get("listing_status"):
                row["listing_status"] = row["listing_status"].lower()
            batch.append(row)
        client.table("classifieds").insert(batch).execute()
        inserted += len(batch)
        if (i // BATCH_SIZE + 1) % 10 == 0:
            log.info("Inserted batch %d/%d (%d records so far)",
                     i // BATCH_SIZE + 1, -(-len(records) // BATCH_SIZE), inserted)
    return inserted


def per_row_upsert(records: list[dict]) -> dict:
    """Fall back to lifecycle upsert when partial data already exists."""
    from shared.db import upsert_classified_record
    tally = {"inserted": 0, "updated": 0, "skipped": 0}
    for idx, rec in enumerate(records, 1):
        url = rec.get("Listing_url")
        if not url:
            continue
        try:
            result = upsert_classified_record(rec)
            tally[result] = tally.get(result, 0) + 1
        except Exception as e:
            log.error("upsert_classified_record failed for %s: %s", url, e)
        if idx % 500 == 0:
            log.info("Per-row upsert progress: %d/%d", idx, len(records))
    return tally


def main():
    records = load_csv(CSV_PATH)
    if not records:
        log.error("No records found — aborting")
        sys.exit(1)

    from shared.db import get_client
    client = get_client()

    # Check how many DuPont records are already in Supabase
    count_result = (
        client.table("classifieds")
        .select("record_id", count="exact")
        .eq("source", SOURCE_DOMAIN)
        .execute()
    )
    existing_count = count_result.count or 0
    log.info("Existing DuPont records in Supabase: %d", existing_count)

    if existing_count == 0:
        log.info("No prior records — using fast bulk INSERT (batches of %d)", BATCH_SIZE)
        inserted = bulk_insert(client, records)
        print(f"Bulk inserted {inserted} DuPont Registry records to Supabase")
    else:
        log.info(
            "Partial data found (%d rows) — using per-row lifecycle upsert for %d records",
            existing_count, len(records),
        )
        tally = per_row_upsert(records)
        print(
            f"Classifieds upsert: {tally['inserted']} inserted, "
            f"{tally['updated']} updated, {tally['skipped']} unchanged"
        )

    # Mark stale Active rows as Removed
    try:
        from shared.db import mark_removed_classifieds
        active_urls = {rec["Listing_url"] for rec in records if rec.get("Listing_url")}
        removed = mark_removed_classifieds(SOURCE_DOMAIN, active_urls)
        if removed:
            print(f"Marked {removed} prior listings as Removed")
    except Exception as e:
        log.error("mark_removed_classifieds failed: %s", e)

    print(f"\nDone! {len(records)} records processed.")


if __name__ == "__main__":
    main()
